#!/usr/bin/env node
// Builds web/team-preview-data.js from the FireRed decomp so the site can
// preview a day's six species without booting the emulator.
//
//   node scripts/gen-team-preview-data.mjs
import { writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { baseStatTotal, SPECIES } from '../tests/party.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const NUM_SPECIES = 412; // SPECIES_EGG in include/constants/species.h

const totals = new Array(NUM_SPECIES).fill(0);
const names = new Array(NUM_SPECIES).fill('');
for (let id = 1; id < NUM_SPECIES; id++) {
  names[id] = SPECIES.get(id) ?? `SPECIES_${id}`;
  try {
    totals[id] = baseStatTotal(id);
  } catch {
    totals[id] = 0;
  }
}

const out = `// Auto-generated by scripts/gen-team-preview-data.mjs — do not edit by hand.
// Base-stat totals and species names for Daily Gold team previews.

export const NUM_SPECIES = ${NUM_SPECIES};
export const BASE_STAT_TOTALS = ${JSON.stringify(totals)};
export const SPECIES_NAMES = ${JSON.stringify(names)};
`;

const path = join(ROOT, 'web/team-preview-data.js');
writeFileSync(path, out);
console.log(`Wrote ${path} (${NUM_SPECIES} species)`);
